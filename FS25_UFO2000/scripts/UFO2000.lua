local function drawText(x, y, size, text, alignment, color)
    setTextColor(color[1], color[2], color[3], color[4] or 1)
    setTextAlignment(alignment or RenderText.ALIGN_LEFT)
    renderText(x, y, size, text)
    setTextAlignment(RenderText.ALIGN_LEFT)
    setTextColor(1, 1, 1, 1)
end

function UFO2000.drawHud(vehicle)
    local spec = vehicle.spec_ufo2000
    if spec == nil or g_currentMission == nil then
        return
    end
    if vehicle.getIsEntered == nil or not vehicle:getIsEntered() then
        return
    end
    -- never draw over an open game menu
    if g_gui ~= nil and g_gui.getIsGuiVisible ~= nil and g_gui:getIsGuiVisible() then
        return
    end

    local white = {1, 1, 1, 1}
    local green = {0.45, 1.0, 0.62, 1}
    local dim = {0.8, 0.9, 1.0, 0.85}

    -- status line, always visible while flying
    if spec.isHovering then
        local altitudeText = string.format("%s %.1f m", g_i18n:getText("ufo_hud_height"), spec.altitude)
        drawText(0.5, 0.09, 0.016, altitudeText, RenderText.ALIGN_CENTER, white)
        local patternName = g_i18n:getText(UFO2000.PATTERNS[spec.patternIndex].name)
        local modeName = spec.beamMode == UFO2000.BEAM_MODE_HARVEST
            and g_i18n:getText("ufo_hud_modeHarvest") or g_i18n:getText("ufo_hud_modeDamage")
        local tank = 0
        local capacity = 0
        if vehicle.getFillUnitFillLevel ~= nil then
            tank = vehicle:getFillUnitFillLevel(UFO2000.HARVEST_TANK_INDEX)
            capacity = vehicle:getFillUnitCapacity(UFO2000.HARVEST_TANK_INDEX)
        end
        local tankLine
        if spec.infiniteTank then
            tankLine = string.format("%s: %s  (%s)", g_i18n:getText("ufo_hud_tank"),
                g_i18n:getText("ufo_hud_tankEndless"), modeName)
        else
            tankLine = string.format("%s: %d / %d l   (%s)", g_i18n:getText("ufo_hud_tank"),
                math.floor(tank), math.floor(capacity), modeName)
        end
        drawText(0.5, 0.092, 0.014, tankLine, RenderText.ALIGN_CENTER, white)
        if spec.unloading or spec.unloadTargetName ~= "" then
            local unloadLine = string.format("%s %s", g_i18n:getText("ufo_hud_unloading"),
                spec.unloadTargetName)
            drawText(0.5, 0.114, 0.014, unloadLine, RenderText.ALIGN_CENTER, green)
        end
        local line
        if UFO2000.isManual(spec.patternIndex) then
            line = string.format("%s: %s  -  %s", g_i18n:getText("ufo_hud_pattern"), patternName,
                g_i18n:getText("ufo_hud_pen"))
        else
            line = string.format("%s: %s  (%s %.1f m)", g_i18n:getText("ufo_hud_pattern"), patternName,
                g_i18n:getText("ufo_hud_radius"), vehicle:getUFOCircleRadius())
        end
        drawText(0.5, 0.068, 0.014, line, RenderText.ALIGN_CENTER, green)
    end

    if not spec.menuOpen then
        return
    end

    -- panel
    local width, height = 0.34, 0.40
    local x, y = 0.5 - width / 2, 0.39
    drawFilledRect(x, y, width, height, 0.02, 0.07, 0.06, 0.72)
    drawOutlineRect(x, y, width, height, 0.002, 0.002, 0.35, 1.0, 0.6, 0.9)

    drawText(0.5, y + height - 0.035, 0.019, g_i18n:getText("ufo_menu_title"), RenderText.ALIGN_CENTER, green)

    for i = 1, UFO2000.getPatternCount() do
        local pattern = UFO2000.PATTERNS[i]
        local rowY = y + height - 0.075 - (i - 1) * 0.026
        local selected = i == spec.patternIndex
        drawText(0.5, rowY, selected and 0.017 or 0.015,
            (selected and "> " or "  ") .. g_i18n:getText(pattern.name) .. (selected and " <" or ""),
            RenderText.ALIGN_CENTER, selected and green or dim)
    end

    local radiusLine
    if UFO2000.isManual(spec.patternIndex) then
        radiusLine = g_i18n:getText("ufo_hud_pen")
    else
        radiusLine = string.format("%s %.1f m   (%s %.1f m)", g_i18n:getText("ufo_hud_radius"),
            vehicle:getUFOCircleRadius(), g_i18n:getText("ufo_hud_height"), spec.altitude)
    end
    drawText(0.5, y + 0.062, 0.014, radiusLine, RenderText.ALIGN_CENTER, white)
    local modeLine = spec.beamMode == UFO2000.BEAM_MODE_HARVEST
        and g_i18n:getText("ufo_hud_modeHarvest") or g_i18n:getText("ufo_hud_modeDamage")
    local focusText = string.format("%s %s: %.2f m   %s", g_i18n:getText("ufo_hud_mode"),
        modeLine, vehicle:getUFOCircleRadius(), g_i18n:getText("ufo_menu_keysMode"))
    drawText(0.5, y + 0.042, 0.013, focusText, RenderText.ALIGN_CENTER, green)
    local tankLine = spec.infiniteTank and g_i18n:getText("ufo_hud_tankEndless")
        or string.format("%d l", math.floor(vehicle:getFillUnitFillLevel(UFO2000.HARVEST_TANK_INDEX)))
    drawText(0.5, y + 0.024, 0.012, string.format("%s %s   %s", g_i18n:getText("ufo_hud_tank"),
        tankLine, g_i18n:getText("ufo_menu_keysTank")), RenderText.ALIGN_CENTER, dim)
    drawText(0.5, y + 0.006, 0.011, g_i18n:getText("ufo_menu_hint"), RenderText.ALIGN_CENTER, dim)
end

