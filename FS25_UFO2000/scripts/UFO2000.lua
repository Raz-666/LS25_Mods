--- true if the crop at the normalised position belongs to the pattern
function UFO2000.isPointInPattern(patternIndex, u, v)
    local pattern = UFO2000.PATTERNS[patternIndex]
    if pattern == nil then
        return false
    end
    return pattern.test(u, v)
end

