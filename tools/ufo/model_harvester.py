"""Model of the FS25_UFO4500 combine (the "real harvester" variant).

The saucer hovers low (2.6 m) so that the driver can see the field over the
header.  It carries:

  * a grain tank with a discharge pipe on the right side (base game `pipe` +
    `dischargeable` specializations take care of the unloading),
  * a cutter attacher joint in front, at header height,
  * a visible "intake chute" between the hull and the header,
  * the same wide invisible wheels as the console mod.

The header itself is generated by model_harvester_header.py.
"""

import math

import model
from meshlib import Mesh, box, cylinder, place, sphere, torus
from model import Node, _fmt
from triggers import VEHICLE, trigger_mask, trigger_node

HOVER = 1.70              # the belly of the saucer is 2.00 m up
WHEEL_RADIUS = 0.55
TRACK_Z = 1.85
TRACK_WIDTH = 0.70
OUTRIGGER_X = 1.95

ATTACH_Y = 1.00           # height of the cutter joint above the ground
ATTACH_Z = 2.30           # ... and how far in front of the origin
PIPE_TIP = (2.50, 2.05, 0.55)

SHIFTED = (
    "visual",
    "collisions",
    "lights",
    "soundMotor",
    "outdoorCameraTarget",
    "indoorCameraTarget",
)


def find(node, name):
    if node.name == name:
        return node
    for child in node.children:
        found = find(child, name)
        if found is not None:
            return found
    return None


def _xyz(node):
    return [float(v) for v in node.attrs.get("translation", "0 0 0").split()]


def _move(node, dy):
    x, y, z = _xyz(node)
    node.attrs["translation"] = "%s %s %s" % (_fmt([x]), _fmt([y + dy]), _fmt([z]))


def chute_mesh():
    """Throat between the hull and the header, so the machine looks connected."""
    m = Mesh()
    # slender neck from the hull down to the header joint
    # (all coordinates are relative to the visual node, which sits HOVER above
    # the vehicle origin - that is why ATTACH_Y is offset by -HOVER here)
    y = ATTACH_Y - HOVER
    m.add("hullPaint", *place(box((0, 0, 0), (0.88, 1.80, 0.78)),
                              rot=(43, 0, 0),
                              translation=(0, y + 0.70, 2.15)))
    m.add("hullMetal", *place(cylinder(0.40, -0.55, 0.30, 16, caps=True),
                              rot=(90, 0, 0),
                              translation=(0, y + 0.05, ATTACH_Z - 0.25)))
    # collar around the joint
    m.add("hullMetal", *place(torus(0.34, 0.07, 0, 24, 8),
                              translation=(0, y + 0.10, ATTACH_Z - 0.10)))
    m.add("hullPaint", *place(box((0, 0, 0), (1.10, 0.16, 0.42)),
                              translation=(0, y + 0.22, ATTACH_Z - 0.05)))
    return m


def pipe_mesh():
    """Grain pipe sticking out to the right side of the saucer."""
    m = Mesh()
    tip_x, tip_y, tip_z = PIPE_TIP
    tip_y -= HOVER
    # out of the belly to the right, with a short spout at the end
    m.add("hullMetal", *place(cylinder(0.15, 0.20, 1.95, 12, caps=True),
                              rot=(0, 0, -90), translation=(0, tip_y, tip_z)))
    m.add("hullMetal", *place(cylinder(0.15, -0.10, 0.30, 12, caps=True),
                              translation=(tip_x, tip_y, tip_z)))
    return m


def build_vehicle_scene():
    root = model.build_scene()

    # 1) lift the craft off the ground
    for name in SHIFTED:
        node = find(root, name)
        if node is None:
            raise RuntimeError("node %r missing in the base model" % name)
        _move(node, HOVER)

    # 2) no tractor beam, no ground ring and no landing legs on a combine
    for name in ("beamNode", "groundRing", "leg0", "leg1", "leg2"):
        node = find(root, name)
        if node is not None:
            node.attrs["visibility"] = "false"

    visual = find(root, "visual")
    visual.add(Node("Shape", "intakeChute", chute_mesh()))
    visual.add(Node("Shape", "grainPipe", pipe_mesh()))

    # 3) two blinking beacon lights inside the cockpit
    visual.add(Node("TransformGroup", "cockpitBeacon1", translation="-0.44 1.62 0.30"))
    visual.add(Node("TransformGroup", "cockpitBeacon2", translation="0.44 1.62 0.30"))

    # 4) cutter attacher joint (below the saucer, in front)
    rotation = root.add(Node("TransformGroup", "attacherRotation",
                             translation="0 %s %s" % (_fmt([ATTACH_Y]), _fmt([ATTACH_Z]))))
    rotation.add(Node("TransformGroup", "attacherJoint"))

    # 5) grain pipe outlets (pipe + dischargeable specializations)
    root.add(trigger_node("pipeTip", (1.6, 1.8, 1.6), PIPE_TIP,
                          mask=trigger_mask(VEHICLE)))
    root.add(Node("TransformGroup", "dischargeNode", translation="%s %s %s"
                  % tuple(_fmt([v]) for v in PIPE_TIP)))

    # 6) invisible wheels (same trick as the console mod)
    for name, z in (("wheelFront", TRACK_Z), ("wheelRear", -TRACK_Z)):
        root.add(Node("TransformGroup", name,
                      translation="0 %s %s" % (_fmt([WHEEL_RADIUS]), _fmt([z]))))
    for name, x in (("wheelOutriggerLeft", -OUTRIGGER_X), ("wheelOutriggerRight", OUTRIGGER_X)):
        root.add(Node("TransformGroup", name,
                      translation="%s %s 0" % (_fmt([x]), _fmt([WHEEL_RADIUS]))))

    return root


def write(path):
    root = build_vehicle_scene()
    return model.write_i3d(root, path, asset_name="ufo4500")


if __name__ == "__main__":
    import os
    import sys
    here = os.path.dirname(os.path.abspath(__file__))
    repo = os.path.dirname(os.path.dirname(here))
    out = os.path.join(repo, "build", "ufo4500_inline.i3d")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    stats, mappings = write(out)
    print("%d shapes, %d tris -> %s" % (stats["shapes"], stats["tris"], out))
    sys.exit(0)
